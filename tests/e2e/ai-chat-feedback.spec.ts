import { test, expect } from '@playwright/test';
import { PrismaClient } from '@prisma/client';
import { readFileSync, writeFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { signAccount } from '../helpers/account-fixture';
test.skip(!process.env.AI_FEEDBACK_FIXTURE || !/^\/sdg_ai_governance_test_\d+$/.test(new URL(process.env.DATABASE_URL ?? 'postgresql://localhost/none').pathname), 'Isolated DB and mocked provider required');
test.setTimeout(120000);
const db = new PrismaClient();
const account = process.env.AI_FEEDBACK_FIXTURE ? JSON.parse(readFileSync(process.env.AI_FEEDBACK_FIXTURE, 'utf8')) : null;
test.afterAll(() => db.$disconnect());
test('chat explains persisted, preflight and browser failures once and preserves recovery', async ({ page, context }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await signAccount(context, account); await page.setViewportSize({ width: 1440, height: 1000 }); await page.goto('/?aiChat=new');
  const chat = page.getByRole('region', { name: 'Trợ lý AI', exact: true }), log = chat.getByRole('log');
  const input = chat.getByRole('textbox', { name: 'Yêu cầu AI' }), send = chat.getByRole('button', { name: 'Gửi yêu cầu', exact: true });
  await expect(input).toBeEnabled({ timeout: 90000 });
  await input.fill('Kiểm thử thông báo hạn mức'); await send.click();
  await expect(log).toContainText('OpenAI báo kết nối đã hết hạn mức sử dụng.', { timeout: 30000 });
  await expect(log.getByText('Cách xử lý:', { exact: false })).toHaveCount(1);
  await expect(chat.locator('form [role=alert]')).toHaveCount(0);
  await expect(log.getByRole('button', { name: 'Chỉnh lại yêu cầu' })).toHaveCount(0);
  await expect(input).toHaveValue('Kiểm thử thông báo hạn mức');
  await page.reload(); await expect(log).toContainText('Billing');
  await page.screenshot({ path: 'outputs/ai-chat-feedback/desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 }); await page.evaluate(() => document.documentElement.classList.add('dark'));
  await expect(log.getByLabel('Lý do chưa hoàn tất yêu cầu')).toBeVisible();
  writeFileSync('outputs/ai-chat-feedback/mobile-metrics.json', JSON.stringify(await page.evaluate(() => ({width:innerWidth,scroll:document.documentElement.scrollWidth,overflow:Array.from(document.querySelectorAll('body *')).filter(e=>e.getBoundingClientRect().right>innerWidth+1).map(e=>({tag:e.tagName,cls:e.className,right:e.getBoundingClientRect().right,text:e.textContent?.slice(0,80)})).slice(0,15)}))));
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'outputs/ai-chat-feedback/mobile-dark.png' });
  await chat.getByRole('button', { name: 'Chat mới', exact: true }).click();
  let intercepted = false;
  await page.route('**/*', async route => {
    if (!intercepted && route.request().method() === 'POST' && route.request().headers()['next-action']) { intercepted = true; await route.abort('failed'); }
    else await route.continue();
  });
  await input.fill('Kiểm thử mất kết nối'); await send.click();
  await expect(log).toContainText('Trình duyệt chưa nhận được kết quả');
  await expect(input).toHaveValue('Kiểm thử mất kết nối'); await expect(chat.locator('form [role=alert]')).toHaveCount(0);
  await send.click(); await expect(log).toContainText('OpenAI báo kết nối đã hết hạn mức sử dụng.');
  await expect(log).not.toContainText('Trình duyệt chưa nhận được kết quả');
  const requests = await db.tin_nhan_ai.count({ where: { company_id: account.company_id, vai_tro: 'NGUOI_DUNG', noi_dung: 'Kiểm thử mất kết nối' } });expect(requests).toBe(1);
  await chat.getByRole('button', { name: 'Chat mới', exact: true }).click();
  await db.nhat_ky_hoat_dong.createMany({ data: Array.from({ length: 10 }, () => ({ company_id: account.company_id, account_id: account.id, ten_dang_nhap: 'test-feedback', ho_ten: 'Người thử thông báo', phan_he: 'AI', hanh_dong: 'AI_REQUEST', doi_tuong_id: 'ai:'+randomUUID(), mo_ta: 'Test rate limit' })) });
  await input.fill('Kiểm thử giới hạn gửi'); await send.click();
  await expect(log).toContainText('10 yêu cầu trong 5 phút'); await expect(log).toContainText('Cách xử lý:');
  await expect(chat.locator('form [role=alert]')).toHaveCount(0); await expect(input).toHaveValue('Kiểm thử giới hạn gửi');
  await chat.getByRole('button', { name: 'Chat mới', exact: true }).click(); await expect(log).not.toContainText('10 yêu cầu');
  expect(errors).toEqual([]);
});
