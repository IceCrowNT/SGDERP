import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { PrismaClient } from '@prisma/client';
import { PDFDocument } from 'pdf-lib';
import { signAccount } from '../helpers/account-fixture';
import { parseAttachment } from '../../src/lib/ai-attachment-parser';
const db=new PrismaClient();
const f=JSON.parse(readFileSync(process.env.TASK_TEST_FIXTURES!,'utf8'));
test.beforeAll(()=>expect(new URL(process.env.DATABASE_URL!).pathname).toMatch(/^\/sdg_tasks_test_\d+$/));
test.afterAll(()=>db.$disconnect());
for (const kind of ['text','scan']) test(`PDF ${kind}: read -> Word -> edit -> export -> verify, private immutable files`,async({page,context})=>{
  test.setTimeout(180000);
  await signAccount(context,f.accounts.requester);
  await page.goto('/?aiChat=new');
  const chat=page.getByRole('region',{name:'Trợ lý AI',exact:true});
  const input=chat.getByRole('textbox',{name:'Yêu cầu AI',exact:true});
  await expect(input).toBeEnabled();
  await expect(chat.getByLabel('Chọn tệp đính kèm',{exact:true})).toBeEnabled();
  const source=await PDFDocument.create();source.addPage().drawText('Quotation: quantity 20, unit price 100, total 2000.');
  const bytes=kind==='scan'?readFileSync('outputs/ai-pdf-20261123/scan.pdf'):Buffer.from(await source.save());
  await chat.getByLabel('Chọn tệp đính kèm',{exact:true}).setInputFiles({name:`quote-${kind}.pdf`,buffer:bytes,mimeType:'application/pdf'});
  await expect(chat.getByRole('button',{name:`Bỏ tệp quote-${kind}.pdf`,exact:true})).toBeEnabled({timeout:30000});
  await input.fill('TEST_PDF_WORKFLOW');await chat.getByRole('button',{name:'Gửi yêu cầu',exact:true}).click();
  await expect(input).toHaveValue('',{timeout:120000});await expect(chat.getByRole('log')).toContainText('Đã kiểm tra PDF kết quả');
  const conversationId=Number(new URL(page.url()).searchParams.get('aiChat'));
  const rows=await db.tep_dinh_kem_ai.findMany({where:{hoi_thoai_id:conversationId},orderBy:{id:'asc'}});
  expect(rows.map(r=>r.loai_tep)).toEqual(['pdf','docx','docx','pdf']);
  const download=async(id:number)=>(await page.request.get(`/media/ai-attachments/${id}`)).body();
  expect(await download(rows[0].id)).toEqual(bytes);
  expect(JSON.stringify((await parseAttachment(await download(rows[1].id),'source.docx')).data)).toContain('20 lọ');
  expect(JSON.stringify((await parseAttachment(await download(rows[2].id),'edited.docx')).data)).toContain('10 lọ');
  expect((await PDFDocument.load(await download(rows[3].id))).getPageCount()).toBeGreaterThan(0);
  expect((rows[3].tom_tat as {sourceIds:number[]}).sourceIds).toContain(rows[2].id);
  await page.reload();await expect(chat.getByRole('link',{name:/quote-final.pdf/})).toBeVisible();
  // A different chat owned by the same account must not read or convert these files.
  await page.goto('/?aiChat=new');await input.fill(`TEST_PDF_FOREIGN ${rows[0].id}`);
  await chat.getByRole('button',{name:'Gửi yêu cầu',exact:true}).click();
  await expect(input).toHaveValue('',{timeout:30000});await expect(chat.getByRole('log')).toContainText('Đã chặn tệp ngoài cuộc chat');
  await signAccount(context,f.accounts.noRights);
  expect((await page.request.get(`/media/ai-attachments/${rows[3].id}`)).status()).toBe(404);
});
