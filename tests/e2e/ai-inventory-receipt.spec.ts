import { test, expect } from '@playwright/test';
import { PrismaClient } from '@prisma/client';
import { readFileSync } from 'node:fs';
import { signAccount } from '../helpers/account-fixture';
test.skip(!/^\/sdg_ai_governance_test_\d+$/.test(new URL(process.env.DATABASE_URL ?? 'postgresql://localhost/none').pathname), 'Isolated database and provider mock only');
test.setTimeout(90000);
const db = new PrismaClient();
const fixture = process.env.AI_DASHBOARD_FIXTURE ? JSON.parse(readFileSync(process.env.AI_DASHBOARD_FIXTURE, 'utf8')) : {};
test.afterAll(() => db.$disconnect());
test('purchase proposal edits missing place, confirms once and restores after reload on desktop and mobile', async ({ page, context }) => {
  await signAccount(context, fixture.accounts.manager);
  const place = await db.vi_tri.create({ data: { company_id: fixture.companyId, ten_vi_tri: `Tủ dây cáp kiểm thử ${Date.now()}`, loai_vi_tri: 'KHU_VUC' } });
  await page.setViewportSize({ width: 1512, height: 982 });
  await page.goto('/?aiChat=new');
  const input = page.getByRole('textbox', { name: 'Yêu cầu AI' });
  await expect(input).toBeEnabled({ timeout: 30000 });
  await input.fill('TEST_RECEIPT vừa mua 2 dây HDMI'); await input.press('Enter');
  const panel = page.getByRole('complementary', { name: 'Chi tiết công việc AI', exact: true });
  await expect(panel.getByText('Ghi nhận hàng vừa mua', { exact: true })).toBeVisible({ timeout: 30000 });
  await expect(panel.getByRole('button', { name: 'Xác nhận nhập hàng', exact: true })).toBeDisabled();
  const countBefore = await db.giao_dich_vat_tu.count({ where: { company_id: fixture.companyId } });
  await panel.getByRole('button', { name: 'Chỉnh sửa bảng', exact: true }).click();
  await panel.getByRole('button', { name: 'Cập nhật bảng', exact: true }).click();
  await expect(panel.getByText('Chọn nơi giữ phụ kiện', { exact: true })).toBeVisible();
  await panel.getByRole('combobox', { name: 'Nơi giữ', exact: true }).click();
  await page.getByRole('option', { name: place.ten_vi_tri, exact: true }).click();
  await panel.getByRole('button', { name: 'Cập nhật bảng', exact: true }).click();
  await expect(panel.getByRole('button', { name: 'Xác nhận nhập hàng', exact: true })).toBeEnabled();
  expect(await db.giao_dich_vat_tu.count({ where: { company_id: fixture.companyId } })).toBe(countBefore);
  await page.screenshot({ path: 'outputs/ai-receipt/desktop.png' });
  await panel.getByRole('button', { name: 'Xác nhận nhập hàng', exact: true }).click();
  await expect(panel.getByText('Đã hoàn tất', { exact: true })).toBeVisible();
  expect(await db.giao_dich_vat_tu.count({ where: { company_id: fixture.companyId } })).toBe(countBefore + 1);
  const row = await db.mat_hang_vat_tu.findFirstOrThrow({ where: { company_id: fixture.companyId, ten_mat_hang: 'Dây HDMI thử' } });
  expect(await db.giao_dich_vat_tu.count({ where: { mat_hang_vat_tu_id: row.id, vi_tri_nhap_id: place.id, loai_giao_dich: 'NHAP', so_luong: 2 } })).toBe(1);
  await page.reload();
  await page.getByRole('button', { name: 'Xem công việc đã lập', exact: true }).last().click();
  await expect(panel.getByText('Đã hoàn tất', { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => document.documentElement.classList.add('dark'));
  await page.screenshot({ path: 'outputs/ai-receipt/mobile-dark.png' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(panel.getByRole('link', { name: 'Xem Dây HDMI thử', exact: true })).toBeVisible();
  await expect(panel.getByRole('link', { name: 'Xem Dây HDMI thử', exact: true })).toHaveAttribute('href', `/inventory?kind=accessory&item=${row.id}`);
  await panel.getByRole('button', { name: 'Tải trạng thái', exact: true }).click();
  expect(await db.giao_dich_vat_tu.count({ where: { company_id: fixture.companyId } })).toBe(countBefore + 1);
});
